
import random
import time
import requests
from datetime import datetime, timezone

from cooling.controller import adjust_cooling, check_temperature


# AWS API configuration
api_url = api_url = "https://3rqqcfw2va.execute-api.ap-southeast-2.amazonaws.com/readings"

# simulation configuration
monitoring_interval = 15  # 5 minutes
target_temperature = 22.0

# initial server room conditions
temperature = 22.0
humidity = 45.0
cooling_level = 50
workload = 40.0
    
scenario = "normal"


def set_workload(mode):

    global scenario

    scenario = mode

    if mode in ["idle", "recovery"]:
        return 15.0

    elif mode == "normal":
        return 40.0

    elif mode == "heavy":
        return 75.0

    elif mode == "extreme":
        return 100.0

    return 40.0


def update_temperature():

    global temperature

    # heat generated by server workload
    heat_gain = (workload / 100) * 1.2

    # cooling effect
    cooling_effect = (cooling_level / 100) * 0.9

    # natural temperature movement
    natural_exchange = (target_temperature - temperature) * 0.08

    temperature += heat_gain - cooling_effect + natural_exchange

    temperature = round(temperature, 2)


def generate_reading():

    global temperature, humidity
    global workload, cooling_level

    # adjust cooling based on current temperature
    cooling_level = adjust_cooling(temperature, cooling_level)

    # check temperature condition
    status = check_temperature(temperature)

    reading = {
        "device_id": "server_room_001",
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "temperature": temperature,
        "humidity": humidity,
        "workload": workload,
        "cooling_level": cooling_level,
        "status": status,
        "scenario": scenario,
        "data_source": "simulated"
    }

    # update humidity
    humidity = round(
        max(30, min(65, humidity + random.uniform(-1, 1))),
        2
    )

    # calculate next temperature
    update_temperature()

    return reading


def display_reading(reading):

    print("\nSERVER ROOM MONITORING")
    print("------------------------------")

    print(f"Scenario: {reading['scenario']}")
    print(f"Temperature: {reading['temperature']} °C")
    print(f"Humidity: {reading['humidity']}%")
    print(f"Server Workload: {reading['workload']}%")
    print(f"Cooling Level: {reading['cooling_level']}%")
    print(f"Status: {reading['status']}")
    print(f"Timestamp: {reading['timestamp']}")

    print("------------------------------")


def send_to_aws(reading):

    try:

        response = requests.post(
            api_url,
            json=reading,
            timeout=10
        )

        response.raise_for_status()

        print("AWS upload successful.")
        print(f"Response: {response.text}")

    except requests.exceptions.RequestException as error:

        print(f"AWS upload failed: {error}")


def run_simulator():

    global workload

    print("\nSERVER ROOM SIMULATOR")
    print("==============================")
    print("1. Idle")
    print("2. Normal")
    print("3. Heavy")
    print("4. Extreme")
    print("5. Recovery")

    choice = input("\nSelect workload scenario: ")

    scenarios = {
        "1": "idle",
        "2": "normal",
        "3": "heavy",
        "4": "extreme",
        "5": "recovery"
    }

    if choice not in scenarios:
        print("Invalid selection.")
        return

    workload = set_workload(scenarios[choice])

    print(f"\nStarting {scenario} simulation.")
    print(f"Monitoring interval: {monitoring_interval // 60} minutes")
    print("Readings will automatically upload to AWS.")
    print("Press CTRL + C to stop.")

    try:

        while True:

            reading = generate_reading()

            display_reading(reading)

            send_to_aws(reading)

            print("\nWaiting 5 minutes for next reading...")

            time.sleep(monitoring_interval)

    except KeyboardInterrupt:

        print("\nSimulation stopped.")


if __name__ == "__main__":
    run_simulator()
